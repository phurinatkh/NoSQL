create table unit (
  unit_id           integer generated by default as identity primary key,
  base_unit_id      integer references unit(unit_id),
  name              varchar(100) not null,
  symbol            varchar(30),
  dimension         varchar(50),
  conversion_factor numeric(18,6)
);

create table location (
  location_id        integer generated by default as identity primary key,
  parent_location_id integer references location(location_id),
  name               varchar(150) not null,
  location_type      varchar(20) not null,
  country_code       varchar(10),
  province_code      varchar(20)
);

create table crop (
  crop_id  integer generated by default as identity primary key,
  name     varchar(150) not null,
  category varchar(100)
);

create table source (
  source_id        integer generated by default as identity primary key,
  source_code      varchar(20) not null unique,
  title            varchar(255) not null,
  publisher        varchar(255),
  publication_year integer,
  url              text,
  accessed_at      date,
  license          varchar(255)
);

create table dataset (
  dataset_id integer generated by default as identity primary key,
  source_id  integer not null references source(source_id),
  title      varchar(255) not null,
  year       integer,
  url        text
);

create table flow (
  flow_id        integer generated by default as identity primary key,
  name           varchar(255) not null,
  flow_type      varchar(50),
  compartment    varchar(100),
  subcompartment varchar(100)
);

create table process (
  process_id         integer generated by default as identity primary key,
  crop_id            integer references crop(crop_id),
  location_id        integer references location(location_id),
  dataset_id         integer references dataset(dataset_id),
  reference_unit_id  integer references unit(unit_id),
  reference_flow_id  integer references flow(flow_id),
  name               varchar(255) not null,
  reference_year     integer,
  reference_amount   numeric(20,6),
  system_boundary    varchar(255),
  cultivation_method varchar(255)
);

create table lci_exchange (
  exchange_id integer generated by default as identity primary key,
  process_id  integer not null references process(process_id),
  flow_id     integer not null references flow(flow_id),
  unit_id     integer not null references unit(unit_id),
  source_id   integer references source(source_id),
  direction   varchar(20) not null,
  amount      numeric(20,6) not null,
  data_year   integer
);

create table agricultural_stat (
  stat_id     integer generated by default as identity primary key,
  crop_id     integer not null references crop(crop_id),
  location_id integer not null references location(location_id),
  dataset_id  integer not null references dataset(dataset_id),
  unit_id     integer not null references unit(unit_id),
  year        integer not null,
  month       integer,
  stat_type   varchar(50) not null,
  value       numeric(20,4) not null,
  season      varchar(20)
);